"""从一份 JSON 契约同时生成服务端与客户端代码（HTTP 接口）。

为什么要有这个脚本
------------------
同一个 HTTP 接口如果服务端写一遍 DTO、客户端再写一遍，两边一定会漂移：某个字段改名、某个类型从
int 变 long，编译器不会告诉你，只有线上 400 或反序列化失败会。这跟协议层"不要手写两份 KCP"是同一条
纪律：**单一真相源 + 生成 + 漂移即失败**。

契约怎么写
----------
    contracts/login.json
    {
      "api": "LoginApi",                 # 生成类名前缀（接口/端点/客户端都基于它）
      "title": "登录与配置",              # 只用于注释
      "endpoints": [
        {
          "id": "Login",                 # 生成的方法名：LoginAsync
          "method": "POST",              # v1 只支持 GET / POST
          "path": "/api/login",
          "summary": "账号密码登录",
          "request":  { "type": "LoginReq", "fields": [ {"name":"Account","type":"string"} ] },
          "response": { "type": "LoginRes", "fields": [ {"name":"Token","type":"string"} ] }
        }
      ]
    }

字段类型：string / int / long / float / double / bool；`"nullable": true` 生成 `int?` 之类。

生成什么
--------
服务端（src/EFramework.Http/Api/Generated/）：
    <Api>.Contracts.g.cs   DTO（System.Text.Json 特性，camelCase 上线）
    <Api>.Endpoints.g.cs   路径常量 + IXxxApi 接口 + MapXxx(WebApplication, IXxxApi)

客户端（Assets/NetApi/Generated/）：
    <Api>.Contracts.g.cs   DTO（Newtonsoft 特性，camelCase 上线）
    <Api>.Client.g.cs      路径常量 + XxxClient（调用 HttpManager）

手写部分（不被覆盖）：服务端实现 IXxxApi 的类、客户端 new XxxClient(baseUrl) 的调用点。

用法
----
    python tools/gen-http-api.py                     # 生成全部契约
    python tools/gen-http-api.py --check             # 只校验；有漂移退出码 1（可挂 CI）
    python tools/gen-http-api.py --contract contracts/login.json
    python tools/gen-http-api.py --out-server <dir> --out-client <dir>
"""
import argparse
import json
import os
import sys

# 生成文件头：明确"这是生成物"，避免有人手改后被下次生成覆盖
HEADER = """/*
 * ================================================
 * Describe:      {describe}
 * Generated by:  tools/gen-http-api.py from {source}
 * CreationTime:  (generated)
 * ScriptVersion: 1.0
 * ===============================================
 *
 * 本文件由契约生成，请勿手改：改 contracts/*.json 后重新运行
 *     python tools/gen-http-api.py
 * 手写实现请放到同目录之外的独立文件（服务端实现 IXxxApi 接口）。
 *
 * Generated from the contract; do not edit by hand. Change contracts/*.json and re-run the generator.
 */
"""

SUPPORTED_METHODS = ("GET", "POST")
SUPPORTED_TYPES = {
    "string": "string",
    "int": "int",
    "long": "long",
    "float": "float",
    "double": "double",
    "bool": "bool",
}

SERVER_NAMESPACE = "EasyFramework.Http.Api.Generated"
CLIENT_NAMESPACE = "EasyFramework.Api.Generated"


def repo_root():
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def default_client_dir(root):
    """自动探测 Unity 工程：<root>/../../Unity/EFramework_Package/EF_Unity/Assets/NetApi/Generated。

    找不到就返回 None —— 绝不能"猜一个路径然后创建它"，那样会安静地把代码写到平行目录里，
    而且工具还报成功（本脚本第一版就踩过：算成了 <root>/../Unity，于是生成了 D:/_Projects/CSharp/Unity/...）。
    """
    unity_root = os.path.normpath(os.path.join(root, "..", "..", "Unity", "EFramework_Package", "EF_Unity"))
    if not os.path.isdir(os.path.join(unity_root, "Assets")):
        return None
    return os.path.join(unity_root, "Assets", "NetApi", "Generated")


def load_contract(path):
    with open(path, encoding="utf-8-sig") as handle:
        contract = json.load(handle)

    if not contract.get("api"):
        raise ValueError(f"{path}: missing 'api'")
    endpoints = contract.get("endpoints") or []
    if not endpoints:
        raise ValueError(f"{path}: 'endpoints' is empty")

    seen_ids = set()
    for endpoint in endpoints:
        for key in ("id", "method", "path", "response"):
            if not endpoint.get(key):
                raise ValueError(f"{path}: endpoint missing '{key}'")

        endpoint_id = endpoint["id"]
        if endpoint_id in seen_ids:
            raise ValueError(f"{path}: duplicate endpoint id '{endpoint_id}'")
        seen_ids.add(endpoint_id)

        method = endpoint["method"].upper()
        if method not in SUPPORTED_METHODS:
            raise ValueError(
                f"{path}: endpoint '{endpoint_id}' uses {method}; v1 only generates {', '.join(SUPPORTED_METHODS)}. "
                "把接口改成 POST，或手写 wrapper。")
        endpoint["method"] = method

        # GET 不该带请求体：契约里写了就直接报错，别生成看着能用实则发不出去的代码
        if method == "GET" and endpoint.get("request"):
            raise ValueError(f"{path}: GET endpoint '{endpoint_id}' must not declare a request body")

        for side in ("request", "response"):
            block = endpoint.get(side)
            if not block:
                continue
            if not block.get("type"):
                raise ValueError(f"{path}: endpoint '{endpoint_id}' {side} missing 'type'")
            for field in block.get("fields") or []:
                field_type = field.get("type")
                if field_type not in SUPPORTED_TYPES:
                    raise ValueError(
                        f"{path}: field '{field.get('name')}' has unsupported type '{field_type}' "
                        f"(supported: {', '.join(SUPPORTED_TYPES)})")
                if not field.get("name"):
                    raise ValueError(f"{path}: a field in endpoint '{endpoint_id}' has no name")

    return contract


def cs_type(field):
    base = SUPPORTED_TYPES[field["type"]]
    if field.get("nullable") and base != "string":
        return f"{base}?"
    return base


def lower_first(text):
    return text[:1].lower() + text[1:] if text else text


def camel(name):
    return lower_first(name)


def doc_block(summary, indent):
    if not summary:
        return ""
    pad = " " * indent
    return f"{pad}/// <summary>\n{pad}/// {summary}\n{pad}/// </summary>\n"


def gen_contracts(contract, source, target):
    """DTO 生成：两侧结构相同，只有 JSON 特性不同（各用各自序列化器）。"""
    api = contract["api"]
    attribute_ns = "System.Text.Json.Serialization" if target == "server" else "Newtonsoft.Json"
    attribute = "JsonPropertyName" if target == "server" else "JsonProperty"
    namespace = SERVER_NAMESPACE if target == "server" else CLIENT_NAMESPACE

    lines = [HEADER.format(describe=f"{api} 契约类型（{target}）", source=source)]
    lines.append(f"using {attribute_ns};\n")
    lines.append(f"namespace {namespace}\n{{")

    emitted = set()
    for endpoint in contract["endpoints"]:
        for side in ("request", "response"):
            block = endpoint.get(side)
            if not block or block["type"] in emitted:
                continue
            emitted.add(block["type"])

            summary = f"{endpoint.get('summary', endpoint['id'])}（{'请求' if side == 'request' else '响应'}）"
            lines.append(doc_block(summary, 4).rstrip("\n"))
            lines.append(f"    public sealed class {block['type']}\n    {{")

            fields = block.get("fields") or []
            for index, field in enumerate(fields):
                if index > 0:
                    lines.append("")
                field_doc = field.get("comment") or field["name"]
                lines.append(f"        /// <summary>\n        /// {field_doc}\n        /// </summary>")
                lines.append(f"        [{attribute}(\"{camel(field['name'])}\")]")
                lines.append(f"        public {cs_type(field)} {field['name']} {{ get; set; }}")

            if not fields:
                lines.append("        // 无字段（占位类型，仍保留以便契约演进）")

            lines.append("    }\n")

    lines.append("}")
    return "\n".join(lines) + "\n"


def gen_endpoints(contract, source):
    """服务端：路径常量 + 接口 + Map 扩展。实现留给手写类，生成物里不出现业务。"""
    api = contract["api"]
    lines = [HEADER.format(describe=f"{api} 服务端端点（路径常量 + 接口 + 路由映射）", source=source)]
    lines.append("using System.Threading;\nusing System.Threading.Tasks;\nusing Microsoft.AspNetCore.Builder;\n"
                 "using Microsoft.AspNetCore.Http;\n")
    lines.append(f"namespace {SERVER_NAMESPACE}\n{{")

    # 1) 路径常量：两侧共用同一份字符串，避免手写 "/api/login" 这类魔法串
    lines.append(f"    /// <summary>\n    /// {api} 的路径常量\n    /// </summary>")
    lines.append(f"    public static class {api}Routes\n    {{")
    for index, endpoint in enumerate(contract["endpoints"]):
        if index > 0:
            lines.append("")
        lines.append(f"        /// <summary>{endpoint.get('summary', endpoint['id'])}</summary>")
        lines.append(f"        public const string {endpoint['id']} = \"{endpoint['path']}\";")
    lines.append("    }\n")

    # 2) 接口：业务实现这一层，生成物只管"路由长什么样"
    lines.append(f"    /// <summary>\n    /// {api} 的业务接口：由手写类实现，路由映射只依赖它\n    /// </summary>")
    lines.append(f"    public interface I{api}\n    {{")
    for index, endpoint in enumerate(contract["endpoints"]):
        if index > 0:
            lines.append("")
        request = endpoint.get("request")
        response_type = endpoint["response"]["type"]
        params = []
        if request:
            params.append(f"{request['type']} request")
        params.append("CancellationToken cancellationToken")
        signature = ", ".join(params)
        lines.append(doc_block(endpoint.get("summary", endpoint["id"]), 8).rstrip("\n"))
        lines.append(f"        Task<{response_type}> {endpoint['id']}Async({signature});")
    lines.append("    }\n")

    # 3) Map 扩展：把最小 API 接到接口上，统一处理空返回
    lines.append(f"    /// <summary>\n    /// {api} 的路由映射\n    /// </summary>")
    lines.append(f"    public static class {api}Endpoints\n    {{")
    lines.append(f"        /// <summary>把 {api} 挂到应用上</summary>")
    lines.append(f"        /// <param name=\"app\">HTTP 应用</param>")
    lines.append(f"        /// <param name=\"api\">业务实现</param>")
    lines.append(f"        public static void Map{api}(this WebApplication app, I{api} api)\n        {{")
    lines.append("            if (app == null) throw new System.ArgumentNullException(nameof(app));")
    lines.append("            if (api == null) throw new System.ArgumentNullException(nameof(api));\n")

    for endpoint in contract["endpoints"]:
        request = endpoint.get("request")
        response_type = endpoint["response"]["type"]
        handler_params = []
        if request:
            handler_params.append(f"{request['type']} request")
        handler_params.append("CancellationToken cancellationToken")
        call_args = "request, cancellationToken" if request else "cancellationToken"

        lines.append(f"            app.Map{endpoint['method'].capitalize()}({api}Routes.{endpoint['id']}, "
                     f"async ({', '.join(handler_params)}) =>")
        lines.append("            {")
        lines.append(f"                {response_type} response = await api.{endpoint['id']}Async({call_args})"
                     ".ConfigureAwait(false);")
        lines.append("                return response == null ? Results.StatusCode(StatusCodes.Status500InternalServerError) : Results.Ok(response);")
        lines.append("            });")
        lines.append("")

    if lines and lines[-1] == "":
        lines.pop()
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines).rstrip("\n") + "\n"


def gen_client(contract, source):
    """客户端：路径常量 + 强类型调用封装（走 HttpManager，UniTask）。"""
    api = contract["api"]
    lines = [HEADER.format(describe=f"{api} 客户端（路径常量 + 强类型调用）", source=source)]
    lines.append("using System;\nusing System.Threading;\nusing Cysharp.Threading.Tasks;\n"
                 "using EasyFramework.Systems.Http;\n")
    lines.append(f"namespace {CLIENT_NAMESPACE}\n{{")

    lines.append(f"    /// <summary>\n    /// {api} 的路径常量（与服务端生成物保持一致）\n    /// </summary>")
    lines.append(f"    public static class {api}Routes\n    {{")
    for index, endpoint in enumerate(contract["endpoints"]):
        if index > 0:
            lines.append("")
        lines.append(f"        /// <summary>{endpoint.get('summary', endpoint['id'])}</summary>")
        lines.append(f"        public const string {endpoint['id']} = \"{endpoint['path']}\";")
    lines.append("    }\n")

    lines.append(f"    /// <summary>\n    /// {api} 客户端：只做 URL 拼接与调用转发，不含业务\n    /// </summary>")
    lines.append(f"    public sealed class {api}Client\n    {{")
    lines.append("        private readonly string _baseUrl;\n")
    lines.append("        /// <summary>构造客户端</summary>")
    lines.append("        /// <param name=\"baseUrl\">服务端根地址（如 ProjectConfig.InnerUrl）</param>")
    lines.append(f"        public {api}Client(string baseUrl)\n        {{")
    lines.append("            if (string.IsNullOrEmpty(baseUrl)) throw new ArgumentException(\"baseUrl is required\", nameof(baseUrl));")
    lines.append("            _baseUrl = baseUrl.TrimEnd('/');")
    lines.append("        }\n")

    for endpoint in contract["endpoints"]:
        request = endpoint.get("request")
        response_type = endpoint["response"]["type"]
        method = endpoint["id"] + "Async"

        params = []
        if request:
            params.append(f"{request['type']} request")
        params.append("CancellationToken cancellationToken = default")

        lines.append(doc_block(endpoint.get("summary", endpoint["id"]), 8).rstrip("\n"))
        lines.append(f"        public UniTask<{response_type}> {method}({', '.join(params)})")
        lines.append("        {")

        if endpoint["method"] == "GET":
            lines.append(f"            return HttpManager.Instance.GetAsync<{response_type}>(")
            lines.append(f"                _baseUrl + {api}Routes.{endpoint['id']}, null, null, null, cancellationToken);")
        else:
            lines.append(f"            return HttpManager.Instance.PostJsonAsync<{request['type']}, {response_type}>(")
            lines.append(f"                _baseUrl + {api}Routes.{endpoint['id']}, request, null, null, null, cancellationToken);")

        lines.append("        }")
        lines.append("")

    if lines and lines[-1] == "":
        lines.pop()
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines).rstrip("\n") + "\n"


def normalize(text):
    return text.replace("\r\n", "\n")


def write_or_check(path, content, check):
    """写入或校验；返回 (状态, 是否漂移)。"""
    expected = normalize(content)

    if os.path.isfile(path):
        with open(path, encoding="utf-8-sig") as handle:
            current = normalize(handle.read())
        if current == expected:
            return "unchanged", False

    if check:
        return "DRIFT", True

    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(expected)

    return "written", False


def main(argv):
    root = repo_root()
    parser = argparse.ArgumentParser(description="Generate server + client code from HTTP API contracts.")
    parser.add_argument("--contract", default=None, help="single contract file (default: all under contracts/)")
    parser.add_argument("--out-server", default=os.path.join(root, "src", "EFramework.Http", "Api", "Generated"))
    parser.add_argument("--out-client", default=None,
                        help="client output dir (default: <unity>/Assets/NetApi/Generated if found)")
    parser.add_argument("--check", action="store_true", help="verify only; exit 1 when generated files drift")
    args = parser.parse_args(argv)

    contract_dir = os.path.join(root, "contracts")
    if args.contract:
        contract_paths = [os.path.abspath(args.contract)]
    else:
        if not os.path.isdir(contract_dir):
            print(f"[ERROR] contract dir not found: {contract_dir}", file=sys.stderr)
            return 1
        contract_paths = sorted(
            os.path.join(contract_dir, name) for name in os.listdir(contract_dir) if name.endswith(".json"))

    if not contract_paths:
        print("[ERROR] no contract files", file=sys.stderr)
        return 1

    client_dir = args.out_client or default_client_dir(root)
    client_available = bool(client_dir)

    if not client_available:
        print("[WARN] Unity project not found; client code will be skipped.\n"
              "       pass --out-client <dir> to generate it explicitly.", file=sys.stderr)

    drifted = []
    for path in contract_paths:
        source = os.path.relpath(path, root).replace("\\", "/")
        contract = load_contract(path)
        api = contract["api"]

        outputs = [
            (os.path.join(args.out_server, f"{api}.Contracts.g.cs"), gen_contracts(contract, source, "server")),
            (os.path.join(args.out_server, f"{api}.Endpoints.g.cs"), gen_endpoints(contract, source)),
        ]

        if client_available:
            outputs.append((os.path.join(client_dir, f"{api}.Contracts.g.cs"), gen_contracts(contract, source, "client")))
            outputs.append((os.path.join(client_dir, f"{api}.Client.g.cs"), gen_client(contract, source)))

        print(f"\n{source}  (api={api}, endpoints={len(contract['endpoints'])})")
        for out_path, content in outputs:
            state, drift = write_or_check(out_path, content, args.check)
            if drift:
                drifted.append(out_path)
            print(f"  {state:<10} {os.path.relpath(out_path, root)}")

    if args.check:
        if drifted:
            print(f"\n[FAIL] {len(drifted)} file(s) out of date; re-run without --check")
            return 1
        suffix = "" if client_available else " (client skipped)"
        print(f"\n[OK] generated code is up to date{suffix}")
        return 0

    client_text = os.path.relpath(client_dir, root) if client_available else "(skipped)"
    print(f"\n[DONE] {len(contract_paths)} contract(s); server -> {os.path.relpath(args.out_server, root)}, "
          f"client -> {client_text}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
